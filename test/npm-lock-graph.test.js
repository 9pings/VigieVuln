test("collectNpmDeps (yarn v1 / Berry / pnpm): record shape matches the package-lock path", () => {
	for (const [lockName, body, lockType] of [["yarn.lock", YARN_V1, "yarn-v1"], ["yarn.lock", YARN_BERRY, "yarn-berry"], ["pnpm-lock.yaml", PNPM_V9, "pnpm"]]) {
		const dir = project(lockName, body);
		const map = collectNpmDeps(dir);
		const lodash = map.get("npm:lodash");
		assert.equal(lodash.lockType, lockType);
		assert.equal(lodash.scope, "transitive", `${lockType}: lodash scope`);
		assert.equal(lodash.isDev, true, `${lockType}: lodash isDev`);
		assert.equal(lodash.depth, 1, `${lockType}: lodash depth`);
		assert.deepEqual(lodash.via, ["npm:jest-fake"], `${lockType}: lodash via`);
		assert.deepEqual(lodash.viaPaths, [["npm:jest-fake"]], `${lockType}: lodash viaPaths`);
		assert.equal(map.get("npm:jest-fake").isDev, true, `${lockType}: jest-fake isDev`);
		assert.equal(map.get("npm:jest-fake").via, undefined, `${lockType}: a direct dep carries no via chain`);
		assert.equal(map.get("npm:shared").isDev, false, `${lockType}: shared isDev`);
		assert.equal(map.get("npm:app-prod").scope, "prod", `${lockType}: app-prod scope`);
		assert.equal(map.get("npm:orphan-pkg").scope, "transitive", `${lockType}: orphan scope`);
		// Coord-wide record: ms is prod overall (one version is), but each version keeps
		// its own classification for lib/attribution.js.
		const ms = map.get("npm:ms");
		assert.deepEqual([...ms.versions].sort(), ["1.0.0", "2.1.3"]);
		assert.equal(ms.isDev, false);
		fs.rmSync(dir, { recursive: true, force: true });
	}
});

test("collectNpmDeps: per-version graph relations are independent of dev flags; orphans stay unknown", t => {
	for (const [lockName, body] of [
		["yarn.lock", YARN_V1], ["yarn.lock", YARN_BERRY],
		["pnpm-lock.yaml", PNPM_V5], ["pnpm-lock.yaml", PNPM_V6], ["pnpm-lock.yaml", PNPM_V9],
	]) {
		const dir = project(lockName, body);
		t.after(() => fs.rmSync(dir, { recursive: true, force: true }));
		const map = collectNpmDeps(dir);
		assert.deepEqual(map.get("npm:app-prod").versionRelations, { "1.2.0": ["direct"] });
		assert.deepEqual(map.get("npm:jest-fake").versionRelations, { "1.0.0": ["direct"] });
		assert.deepEqual(map.get("npm:lodash").versionRelations, { "4.17.15": ["transitive"] });
		assert.deepEqual(map.get("npm:ms").versionRelations, { "1.0.0": ["transitive"], "2.1.3": ["transitive"] });
		assert.deepEqual(map.get("npm:orphan-pkg").versionRelations, { "1.0.0": ["unknown"] });
	}
});

