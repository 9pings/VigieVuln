/**
 * yarn (v1 + Berry) and pnpm (v5/v6/v9) lockfiles: dev/prod + direct/transitive
 * classification must come from the dependency GRAPH walked from the package.json
 * roots — the same contract the package-lock path honours.
 *
 * Before the fix every yarn entry was emitted `scope:"prod", depth:0` with no isDev,
 * so a devDependency (and everything it pulls in) was gated as production, and every
 * transitive was reported as a direct dep. pnpm got direct dev right but turned every
 * transitive of a dev dep into prod, and every transitive into a "direct".
 *
 * One graph, written in every format:
 *
 *   package.json  dependencies:    app-prod ^1.0.0
 *                 devDependencies: jest-fake 1.0.0
 *
 *   app-prod@1.2.0  → shared@1.0.0, ms@2.1.3
 *   jest-fake@1.0.0 → lodash@4.17.15, shared@1.0.0, ms@1.0.0
 *   lodash@4.17.15  → deep@1.0.1
 *   orphan-pkg@1.0.0   (in the lock, reachable from nothing)
 *
 * Expected:
 *   app-prod   prod        depth 0  isDev false
 *   jest-fake  dev         depth 0  isDev true
 *   lodash     transitive  depth 1  isDev true   via [npm:jest-fake]
 *   deep       transitive  depth 2  isDev true   via [npm:jest-fake, npm:lodash]
 *   shared     transitive  depth 1  isDev false  (reachable from BOTH → prod), via the prod root
 *   ms@2.1.3   transitive           isDev false
 *   ms@1.0.0   transitive           isDev true   (same name, other version, dev-only)
 *   orphan-pkg transitive           isDev false  (never invented as a prod DIRECT)
 */
