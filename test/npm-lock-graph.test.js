function project(lockName, lockBody, pkg = PKG) {
	const dir = fs.mkdtempSync(path.join(os.tmpdir(), "fad-npm-graph-"));
	fs.writeFileSync(path.join(dir, "package.json"), JSON.stringify(pkg));
	fs.writeFileSync(path.join(dir, lockName), lockBody);
	return dir;
}

function byNameVersion(deps) {
	const out = {};
	for (const d of deps) out[`${d.name}@${d.version}`] = d;
	return out;
}

/** The parse-level contract every format must meet on the shared graph. */
function assertGraph(deps, label) {
	const m = byNameVersion(deps);
	const get = k => { assert.ok(m[k], `${label}: ${k} missing (have ${Object.keys(m).join(", ")})`); return m[k]; };

	const appProd = get("app-prod@1.2.0");
	assert.equal(appProd.scope, "prod", `${label}: app-prod scope`);
	assert.equal(appProd.depth, 0, `${label}: app-prod depth`);
	assert.equal(appProd.isDev, false, `${label}: app-prod isDev`);

	const jest = get("jest-fake@1.0.0");
	assert.equal(jest.scope, "dev", `${label}: jest-fake scope`);
	assert.equal(jest.depth, 0, `${label}: jest-fake depth`);
	assert.equal(jest.isDev, true, `${label}: a direct devDependency is dev`);

	const lodash = get("lodash@4.17.15");
	assert.equal(lodash.scope, "transitive", `${label}: lodash is a transitive, not a direct`);
	assert.equal(lodash.depth, 1, `${label}: lodash depth`);
	assert.equal(lodash.isDev, true, `${label}: a transitive of a dev-only root is dev`);
	assert.deepEqual(lodash.via, ["npm:jest-fake"], `${label}: lodash via`);

	const deep = get("deep@1.0.1");
	assert.equal(deep.scope, "transitive", `${label}: deep scope`);
	assert.equal(deep.depth, 2, `${label}: deep depth`);
	assert.equal(deep.isDev, true, `${label}: deep isDev`);
	assert.deepEqual(deep.via, ["npm:jest-fake", "npm:lodash"], `${label}: deep via`);

	const shared = get("shared@1.0.0");
	assert.equal(shared.scope, "transitive", `${label}: shared scope`);
	assert.equal(shared.isDev, false, `${label}: reachable from a prod root AND a dev root → prod`);
	assert.deepEqual(shared.via, ["npm:app-prod"], `${label}: the chain shown is the PRODUCTION one`);

	assert.equal(get("ms@2.1.3").isDev, false, `${label}: ms@2.1.3 (prod path) isDev`);
	assert.equal(get("ms@2.1.3").scope, "transitive", `${label}: ms@2.1.3 scope`);
	assert.equal(get("ms@1.0.0").isDev, true, `${label}: ms@1.0.0 (dev-only path) isDev`);
	assert.equal(get("ms@1.0.0").scope, "transitive", `${label}: ms@1.0.0 scope`);

	const orphan = get("orphan-pkg@1.0.0");
	assert.equal(orphan.scope, "transitive", `${label}: an orphan is never invented as a direct prod dep`);
	assert.equal(orphan.isDev, false, `${label}: orphan isDev mirrors the package-lock path (lock flag, else false)`);
}

