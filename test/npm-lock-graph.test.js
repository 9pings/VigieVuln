test("per-version classification reaches the match: ms@1.0.0 (dev-only) is dev, ms@2.1.3 is prod", () => {
	const dir = project("yarn.lock", YARN_V1);
	const map = collectNpmDeps(dir);
	const ms = map.get("npm:ms");
	// matchOne clones the coord-wide record per version; attribution re-stamps it.
	const matches = ["1.0.0", "2.1.3"].map(v => ({ dep: { ...ms, version: v }, cve: { id: `CVE-X-${v}` } }));
	attributeMatchOrigins(matches);
	assert.equal(matches[0].dep.isDev, true, "ms@1.0.0 is reachable only through jest-fake");
	assert.equal(matches[1].dep.isDev, false, "ms@2.1.3 is reachable through app-prod");
	fs.rmSync(dir, { recursive: true, force: true });
});

test("--ignore-test drops dev-only transitives too, keeps a dep reachable from prod", () => {
	for (const [lockName, body] of [["yarn.lock", YARN_V1], ["yarn.lock", YARN_BERRY], ["pnpm-lock.yaml", PNPM_V9]]) {
		const dir = project(lockName, body);
		const map = collectNpmDeps(dir, { ignoreTest: true });
		assert.equal(map.has("npm:jest-fake"), false, `${lockName}: direct dev dropped`);
		assert.equal(map.has("npm:lodash"), false, `${lockName}: dev-only transitive dropped`);
		assert.equal(map.has("npm:deep"), false, `${lockName}: dev-only transitive (depth 2) dropped`);
		assert.equal(map.has("npm:shared"), true, `${lockName}: shared is reachable from prod`);
		assert.deepEqual(map.get("npm:ms").versions, ["2.1.3"], `${lockName}: only the prod version of ms survives`);
		fs.rmSync(dir, { recursive: true, force: true });
	}
});

