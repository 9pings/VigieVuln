/** Every <version> in a maven-metadata.xml body, in document order. */
function parseMavenMetadataVersions(xml) {
	if (!xml) return [];
	return [...xml.matchAll(/<version>([^<]+)<\/version>/g)].map(m => m[1].trim()).filter(Boolean);
}

/**
 * Publication date of one version, from the POM's Last-Modified header. maven-metadata.xml
 * only carries an artifact-level <lastUpdated>, so the date has to come from the file itself;
 * a HEAD costs no body. Measured against Solr's timestamps on
 * 25 coordinates: 20 exact, 22 within two days, the rest old artifacts whose storage was
 * touched after publication. Best-effort — a null date just leaves the column empty.
 */
/** Central + private repos, mirrors dropped. Exported so the choice is testable. */
function pomLastModifiedRepos(repos) {
	const direct = (repos || []).filter(r => !r.mirror);
	return direct.length ? direct : (repos || []);
}

async function pomLastModified(repos, groupId, artifactId, version, opts = {}) {
	try {
		const { tryRepos } = require("./maven-repo");
		const p = `${groupId.replace(/\./g, "/")}/${artifactId}/${version}/${artifactId}-${version}.pom`;
		// Central and private repositories only — NOT the mirror rotation. maven-metadata.xml is
		// a small, constantly re-requested file that the mirrors serve hot; an individual .pom is
		// a unique deep path that is cold in their buckets. Measured on 171 coordinates, both
		// orderings to rule out CDN warming: 1.8s / 1.7s via Central against 9.2s via the
		// rotation, with zero misses either way. Private repos stay in — a private artifact's
		// POM exists nowhere else.
		const hit = await tryRepos(pomLastModifiedRepos(repos), p, {
			method: "HEAD", key: `${groupId}:${artifactId}`, health: opts.health,
			userAgent: "vigievuln-outdated-checker",
		});
		const lm = hit?.response?.headers?.get?.("last-modified");
		if (!lm) return null;
		const d = new Date(lm);
		return Number.isNaN(d.getTime()) ? null : d.toISOString().slice(0, 10);
	} catch { return null; }
}

/**
 * Latest published version of a coordinate.
 *
 * maven-metadata.xml over the repository rotation comes FIRST. It is a static file on the
 * CDN, spread across Central plus the officially listed mirrors, and it reaches private
 * repositories too. Measured on 165 real coordinates from a 105-module reactor:
 * metadata answered 165/165 in 7.6 s, Solr answered 82/165 in 222 s — and Solr's index was
 * STALE on 92 of them, every single disagreement in the same direction (it reported
 * logback-classic 1.5.18 when 1.6.3 was published, netty-all 4.2.1.Final against 4.2.18.Final).
 * So this is a correctness fix that happens to be 29× faster, not an optimisation.
 *
 * Solr remains the fallback: it still answers for coordinates whose metadata cannot be read,
 * and it carries a publication timestamp of its own.
 */
async function fetchLatestVersion(groupId, artifactId, cache, opts = {}) {
	const key = `${groupId}:${artifactId}`;
	if (cache.entries[key]) return cache.entries[key];
	if (opts.offline) return null;

	if (Array.isArray(opts.repos) && opts.repos.length) {
		try {
			const { fetchMavenMetadata } = require("./maven-repo");
			const hit = await fetchMavenMetadata(opts.repos, groupId, artifactId, {
				userAgent: "vigievuln-outdated-checker", health: opts.health,
			});
			if (hit?.body) {
				// <release> is "latest non-SNAPSHOT" and will happily name a beta, so pick the
				// highest STABLE version instead — unless the dep is already on a pre-release.
				const latest = latestStableVersion(parseMavenMetadataVersions(hit.body), { current: opts.currentVersion })
					|| parseMavenMetadataLatest(hit.body);
				if (latest) {
					const entry = {
						latest,
						releaseDate: await pomLastModified(opts.repos, groupId, artifactId, latest, opts),
						source: hit.repo.name || hit.repo.url,
					};
					cache.entries[key] = entry;
					return entry;
				}
			}
		} catch { /* fall through to Solr */ }
	}

	try {
		const url = `https://search.maven.org/solrsearch/select?q=g:%22${encodeURIComponent(groupId)}%22+AND+a:%22${encodeURIComponent(artifactId)}%22&core=gav&rows=1&wt=json`;
		const res = await require("./providers").getResource("maven", "latest", { group: groupId, artifact: artifactId },
			{ headers: { "User-Agent": "vigievuln-outdated-checker" } });
		if (res.ok) {
			const doc = (await res.json())?.response?.docs?.[0];
			if (doc) {
				const entry = { latest: doc.v, releaseDate: doc.timestamp ? new Date(doc.timestamp).toISOString().slice(0, 10) : null, source: "central-solr" };
				cache.entries[key] = entry;
				return entry;
			}
		}
	} catch { /* nothing left to try */ }

	cache.entries[key] = { error: "not found" };
	return cache.entries[key];
}

/**
 * Pull the "latest" version from a maven-metadata.xml body. Prefers
 * <versioning><release> (stable), falls back to <versioning><latest> and
 * then the highest entry in <versioning><versions>.
 */
function parseMavenMetadataLatest(xml) {
	if (!xml) return null;
	const release = xml.match(/<release>([^<]+)<\/release>/);
	if (release?.[1]) return release[1].trim();
	const latest = xml.match(/<latest>([^<]+)<\/latest>/);
	if (latest?.[1]) return latest[1].trim();
	const versions = [...xml.matchAll(/<version>([^<]+)<\/version>/g)].map(m => m[1].trim()).filter(Boolean);
	if (versions.length) {
		try { versions.sort((a, b) => compareMavenVersions(a, b)); return versions[versions.length - 1]; }
		catch { return versions[versions.length - 1]; }
	}
	return null;
}

async function checkOutdatedDeps(resolvedDeps, opts = {}) {
	const { verbose, offline, concurrency = 8, repos, onProgress } = opts;
	const cache = loadJsonCache(VERSION_CACHE_PATH);
	const fresh = cache.meta?.fetchedAt && (Date.now() - cache.meta.fetchedAt) < VERSION_CACHE_MAX_AGE_MS;
	if (!fresh && !offline) cache.entries = {};
	// Maven Central only — npm/composer/pypi/nuget have their own registries (codec.checkRegistry).
	// Transitives are excluded BEFORE fetching: the Outdated chapter only reports deps you
	// declare and can bump (vigievuln.js drops transitive rows after the fact anyway), and
	// on a real reactor transitives outnumber directs 5-10× — querying Central for versions
	// that never reach the report was where most of this pass's wall-clock went.
	const list = [...resolvedDeps.values()].filter(d =>
		d.version && !/\$\{|SNAPSHOT/i.test(d.version) && d.ecosystem === "maven" && d.scope !== "transitive");
	const results = [];

	// Progress indicator — Maven Central can serve hundreds of deps in a few
	// seconds with 8-way concurrency, but on first run (cold cache) the user
	// would see total silence for 20-60s.
	const liveCount = offline ? 0 : list.filter(d => !cache.entries[`${d.groupId}:${d.artifactId}`]).length;
	if (liveCount && !offline && !onProgress) {
		console.log(`📅 Outdated: checking ${list.length} deps against Maven Central (${liveCount} live, ${list.length - liveCount} cached)…`);
	}

	let cursor = 0;
	let processed = 0;
	const startedAt = Date.now();
	const printOutdatedProgress = (final = false) => {
		if (onProgress) { onProgress(processed, list.length); return; }
		if (!liveCount) return;
		const elapsed = Math.round((Date.now() - startedAt) / 1000);
		const pct = Math.round((processed / list.length) * 100);
		const line = `   outdated: ${processed}/${list.length} (${pct}%) — ${elapsed}s`;
		if (process.stdout.isTTY) process.stdout.write(`\r${line}${final ? "\n" : "          "}`);
		else if (final) console.log(line);
	};
	// Announce the total before any work starts. Ticking only every 10th completion left the
	// step showing a bare spinner until the 10th dependency came back, which on a cold cache
	// is exactly the stretch where the user wants to see something moving.
	if (list.length) printOutdatedProgress();
	const workers = Array.from({ length: concurrency }, async () => {
		while (cursor < list.length) {
			const dep = list[cursor++];
			const entry = await fetchLatestVersion(dep.groupId, dep.artifactId, cache, { offline, repos, currentVersion: dep.version });
			processed++;
			printOutdatedProgress();
			if (!entry?.latest) continue;
			try {
				if (compareMavenVersions(dep.version, entry.latest) < 0) {
					results.push({ dep, latest: entry.latest, releaseDate: entry.releaseDate || null });
					if (verbose) process.stdout.write(`  outdated: ${dep.groupId}:${dep.artifactId} ${dep.version} → ${entry.latest}\n`);
				}
			} catch { /* ignore comparison failure */ }
		}
	});
	await Promise.all(workers);
	if (liveCount) printOutdatedProgress(true);

	if (!offline) {
		if (!fresh) cache.meta = { fetchedAt: Date.now() };
		saveJsonCache(VERSION_CACHE_PATH, cache);
	}
	results.sort((a, b) => `${a.dep.groupId}:${a.dep.artifactId}`.localeCompare(`${b.dep.groupId}:${b.dep.artifactId}`));
	return results;
}

