/**
 * lib/i18n.js — report localisation (en / fr), selected by --lang.
 *
 * The ENGLISH STRING IS THE KEY. `t("Copy table")` returns the French wording under
 * `fr` and the key itself under `en`, so:
 *   - the English report is byte-identical to the one that existed before this file,
 *     which is what makes a 900-test suite asserting exact strings still meaningful;
 *   - a missing translation degrades to English instead of rendering a raw key at a
 *     client, which is the failure mode of every id-keyed catalogue;
 *   - the catalogue reads as a glossary and can be reviewed by someone who does not
 *     read the code.
 *
 * A sentence that carries a value interpolates a {placeholder} rather than being
 * concatenated in source order, because word order differs between languages: the
 * count in "Top {n} most critical" has to be able to move, and a count that decides
 * a plural gives EACH form its own key (the English source picks the form, so an
 * `en` report is unchanged, and a language with different plural rules translates
 * both independently).
 *
 * SCOPE: the report's own chrome only. Text that comes from a data source — CVE
 * descriptions, advisory summaries, registry deprecation reasons, endoflife notes — is
 * NEVER translated: it is evidence, and paraphrasing evidence in an audit is wrong.
 * By the same rule, a CVSS severity (CRITICAL / HIGH / …) stays in NVD's own vocabulary
 * wherever it is rendered as the value of a finding — a badge, a priority band, the
 * per-severity breakdown of the baseline diff — while the report's own labels around it
 * are translated. CWE titles are the one exception (see data/cwe-names-fr.json): they
 * are a fixed vocabulary, and MITRE's original travels with every translated one.
 *
 * @author: N.BRAUN
 * @email: pp9ping@gmail.com
 */

const LOCALES = ["en", "fr"];

/** "us", "en-US", "EN" … → "en"; "fr-FR" → "fr"; anything else → "en". */
function normaliseLocale(raw) {
	const s = String(raw || "").trim().toLowerCase().replace("_", "-");
	if (!s) return "en";
	const base = s.split("-")[0];
	if (base === "us") return "en";
	return LOCALES.includes(base) ? base : "en";
}

