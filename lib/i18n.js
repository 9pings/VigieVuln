const CATALOG = { en: {}, fr };

/**
 * Translator for one locale. `vars` interpolates {name} placeholders, so a sentence
 * can be reordered in translation instead of being concatenated in source order.
 */
function makeT(locale) {
	const loc = normaliseLocale(locale);
	const table = CATALOG[loc] || CATALOG.en;
	return function t(key, vars) {
		let out = (loc !== "en" && table[key] != null) ? table[key] : key;
		// A translation may be [singular, plural]: `vars.n` is the grammatical number and
		// picks the form. English never reaches this branch — its table is empty — so the
		// source string, and with it the English report, is untouched. It exists because a
		// count that English leaves invariant ("3 obsolete", "1 obsolete") does inflect in
		// French, and "1 obsolètes" is the kind of detail an auditor notices.
		if (Array.isArray(out)) out = out[Number(vars && vars.n) > 1 ? 1 : 0];
		if (vars) for (const [k, v] of Object.entries(vars)) out = out.split(`{${k}}`).join(String(v));
		return out;
	};
}

